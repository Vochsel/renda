"""Regenerate spec/fixtures/estimator/hardware.json from the core planner (the source of truth).

web/src/lib/estimate.ts must reproduce every case: engine, hardware, chunk count and the
seconds / wall-seconds ranges. Run from core/: `uv run python scripts/gen_estimator_fixture.py`.
"""

from __future__ import annotations

import itertools
import json
from pathlib import Path

from renda.planner import plan
from renda.spec import load_package

OUT = Path(__file__).resolve().parents[2] / "spec/fixtures/estimator/hardware.json"

SOURCES = {
    "glb": {"scene": {"root": "./model.glb"}},
    "stl": {"scene": {"root": "./part.stl"}},
    "blend": {"scene": {"root": "./scene.blend"}},
    "step": {"scene": {"root": "./bracket.step"}},
    "splat": {"scene": {"root": "./capture.spz"}},
    "mixed": {"scene": {"root": "./room.spz", "include": [{"asset": "./prop.glb"}]}},
}
ENGINE_SOURCES = [("auto", s) for s in ("glb", "stl", "blend", "splat", "mixed")] + [
    ("blender-cycles", "glb"), ("blender-eevee", "glb"), ("blender-workbench", "stl"),
    ("mitsuba", "glb"), ("mitsuba", "step"), ("threejs", "glb"), ("gsplat", "splat"),
]
RESOLUTIONS = [[640, 480], [1920, 1080]]
QUALITIES = ["draft", "standard", "final"]
FRAMES = [None, [1, 120]]
PRIORITIES = ["economy", "standard", "rush"]
HARDWARE = ["auto", "cpu", "gpu"]
EFFECTS = {
    "post": {"post": {"vignette": 0.3, "filmGrain": 0.1}},
    "lens": {"camera": {"mode": "auto", "lens": {"focalLengthMm": 85, "fStop": 1.8}}},
    "motionBlur": {"render": {"motionBlur": {"shutter": 0.5, "subframes": 8}}},
}


def package(engine: str, source: str, res, quality: str, frames, hardware: str, effect: str | None = None) -> dict:
    pkg: dict = {"version": 1, **json.loads(json.dumps(SOURCES[source]))}
    pkg["render"] = {"engine": engine, "resolution": res, "quality": quality, "hardware": hardware}
    if frames:
        pkg["animation"] = {"frames": frames, "fps": 24, "turntable": {"revolutions": 1}}
        pkg["output"] = {"format": "mp4"}
    if effect:
        extra = json.loads(json.dumps(EFFECTS[effect]))
        if "render" in extra:
            pkg["render"].update(extra.pop("render"))
        pkg.update(extra)
    return pkg


def case(pkg: dict, priority: str) -> dict:
    p = plan(load_package(pkg), None, priority)
    return {
        "package": pkg, "priority": priority, "engine": p.engine, "hardware": p.hardware,
        "chunks": len(p.chunks), "estSeconds": list(p.est_seconds), "estWallSeconds": list(p.est_wall_seconds),
    }


def main() -> None:
    cases = []
    for (engine, source), res, q, fr, pr, hw in itertools.product(ENGINE_SOURCES, RESOLUTIONS, QUALITIES, FRAMES, PRIORITIES, HARDWARE):
        cases.append(case(package(engine, source, res, q, fr, hw), pr))
    for engine, effect, pr in itertools.product(["blender-cycles", "blender-eevee", "mitsuba", "threejs", "gsplat"], EFFECTS, PRIORITIES):
        src = "splat" if engine == "gsplat" else "glb"
        cases.append(case(package(engine, src, [1920, 1080], "standard", [1, 48], "auto", effect), pr))
    doc = {
        "_comment": "Generated by core/scripts/gen_estimator_fixture.py from core/renda/planner.py plan(); "
                    "web/src/lib/estimate.ts estimateScene must reproduce engine, hardware, chunks and seconds.",
        "cases": cases,
    }
    OUT.write_text(json.dumps(doc, separators=(",", ":")) + "\n")
    print(f"wrote {len(cases)} cases to {OUT}")


if __name__ == "__main__":
    main()
